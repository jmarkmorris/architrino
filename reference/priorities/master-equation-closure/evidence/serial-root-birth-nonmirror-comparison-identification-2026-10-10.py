"""Identification of the printed seventh-order row with the Taylor polynomial of the comparison response.

The actual-response certificate bounds |R_actual - T_7 Phi_5|, where Phi_5 is the evaluated causal
response of the auxiliary comparison equation whose field F_5 is the canonical pointwise field
truncated at fifth order, and T_7 Phi_5 is its degree-seven Taylor polynomial in alpha. The printed
list in overnight2-a-canonical-seventh-order-row.md is claimed to be that polynomial.

This script computes T_7 Phi_5 separately: it takes this review's own fifth-order pointwise field
(ring expansion of the delayed canonical mirror row), holds it fixed, generates the comparison path's
derivatives from that fixed field, solves the source root and evaluates the canonical response once,
through degree seven. It compares the result with (a) the printed sixth- and seventh-order
coefficients and (b) this review's full self-consistent formal expansion.

It imports only this review's ring script. Exact rational arithmetic; no trajectory. Known cases first:
  - feeding the full third-order field returns that field (fixed point);
  - a first-order field reproduces the response through third order and NOT at fourth order
    (the two-order gain, with its negative side).
It does not compute or use any coefficient beyond degree seven.
"""
import importlib.util
import json
import pathlib
import sys
import time
import sympy as sp

here = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("ring", here / "serial-root-birth-nonmirror-account-rederivation-ring-2026-10-10.py")
ring = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ring)
u, p, q, e, ONE = ring.u, ring.p, ring.q, ring.e, ring.ONE
trunc, dvec, chord, series_pow, qq = ring.trunc, ring.dvec, ring.chord, ring.series_pow, ring.qq
P, Q = ring.m.P, ring.m.Q


def evaluate(A, N):
    """One evaluation of the canonical response through eps^N for a path generated by the fixed field A."""
    ders = [None, (p, q), A]
    for _k in range(3, N + 3):
        ders.append(dvec(ders[-1], A, N))
    Rt = ONE
    for _it in range(N + 1):
        rt = chord(ders, Rt, N)
        Rt = series_pow(trunc(rt[0] ** 2 + rt[1] ** 2 - ONE, N), sp.Rational(1, 2), N)
    rt = chord(ders, Rt, N)
    f = trunc(-2 * e * Rt, N)
    G, pw = [ders[1][0], ders[1][1]], ONE
    for k in range(1, N + 1):
        pw = trunc(pw * f, N)
        for i in (0, 1):
            G[i] = G[i] + trunc(pw * ders[k + 1][i].exquo(u ** k), N) * qq(sp.Rational(1, sp.factorial(k)))
    den = trunc(Rt * Rt * (Rt + e * (rt[0] * G[0] + rt[1] * G[1])), N)
    inv = series_pow(trunc(den - ONE, N), -1, N)
    return tuple(trunc(-u ** 2 * rt[i] * inv, N) for i in (0, 1))


def coeffs(A, N):
    return ring.to_PQ(A, N)


def same(c1, c2):
    return sp.simplify(c1 - c2) == 0


t0 = time.time()
known = {}
A3 = ring.response(3)
E3 = evaluate(A3, 3)
known["full third-order field is a fixed point of the evaluation"] = all(E3[i] == A3[i] for i in (0, 1))
F1 = tuple(trunc(c, 1) for c in ring.response(1))
E4 = evaluate(F1, 4)
a_full4, B_full4 = coeffs(ring.response(4), 4)
a_c4, B_c4 = coeffs(E4, 4)
known["first-order field reproduces the response through third order"] = all(same(a_c4[n], a_full4[n]) for n in range(4)) and all(same(B_c4[n], B_full4[n]) for n in range(3))
# Negative control. The first run of this script tested the radial fourth-order coefficient, which a
# first-order field happens to reproduce as well; the response first differs in its transverse
# fourth-order coefficient Q*B_3 (difference P*Q in B_3). That expectation was this script's error; the
# first-run source and output are retained.
known["and does not reproduce the transverse response at fourth order (negative control)"] = not same(B_c4[3], B_full4[3])
out = {"known": {k: bool(v) for k, v in known.items()}, "known_result": "PASS" if all(known.values()) else "FAIL"}
if out["known_result"] == "PASS" and len(sys.argv) > 1 and sys.argv[1] == "target":
    F5 = ring.response(5)
    a7, B7 = coeffs(evaluate(F5, 7), 7)
    af, Bf = coeffs(ring.response(7), 7)
    doc_ar6 = Q * (2304 * P ** 4 - 25632 * P ** 2 * Q ** 2 + 3408 * P ** 2 * Q + 45 * Q ** 5 + 6240 * Q ** 4 - 672 * Q ** 3 - 224 * Q ** 2) / 720
    doc_ar7 = P * Q * (2088 * P ** 4 - 46728 * P ** 2 * Q ** 2 + 762 * P ** 2 * Q + 40329 * Q ** 4 + 10758 * Q ** 3 - 7832 * Q ** 2) / 630
    doc_at6 = -P * Q ** 2 * (1200 * P ** 2 - 45 * Q ** 3 - 2392 * Q ** 2 - 1248 * Q) / 120
    doc_at7 = -Q ** 2 * (26352 * P ** 4 - 149400 * P ** 2 * Q ** 2 - 107256 * P ** 2 * Q + 28683 * Q ** 4 + 35880 * Q ** 3 - 13928 * Q ** 2) / 2520
    target = {
        "comparison response equals the fifth-order field through degree five": all(same(a7[n], af[n]) for n in range(6)) and all(same(B7[n], Bf[n]) for n in range(5)),
        "T_7 Phi_5 radial degree six equals the printed a_r,6": same(a7[6], doc_ar6),
        "T_7 Phi_5 radial degree seven equals the printed a_r,7": same(a7[7], doc_ar7),
        "T_7 Phi_5 transverse degree six equals the printed a_t,6": same(Q * B7[5], doc_at6),
        "T_7 Phi_5 transverse degree seven equals the printed a_t,7": same(Q * B7[6], doc_at7),
        "T_7 Phi_5 equals the full formal canonical expansion at degrees six and seven": same(a7[6], af[6]) and same(a7[7], af[7]) and same(B7[5], Bf[5]) and same(B7[6], Bf[6]),
    }
    out["target"] = {k: bool(v) for k, v in target.items()}
    out["target_result"] = "PASS" if all(target.values()) else "FAIL"
out["seconds"] = round(time.time() - t0, 2)
print(json.dumps(out, indent=1))
ok = out["known_result"] == "PASS" and (len(sys.argv) < 2 or sys.argv[1] != "target" or out.get("target_result") == "PASS")
raise SystemExit(0 if ok else 1)
