function roundCoordinate(value) {
  return Number(value.toFixed(3));
}

function createGraphenePreset() {
  const rows = 5;
  const columns = 6;
  const bondLength = 0.92;
  const columnSpacing = Math.sqrt(3) * bondLength;
  const rowSpacing = 1.5 * bondLength;
  const atoms = [];
  const atomIndexByKey = new Map();
  const bonds = [];

  function addAtom(key, x, y, z) {
    atomIndexByKey.set(key, atoms.length);
    atoms.push({
      element: "C",
      x: roundCoordinate(x),
      y: roundCoordinate(y),
      z: roundCoordinate(z),
    });
  }

  function addBond(startKey, endKey) {
    const start = atomIndexByKey.get(startKey);
    const end = atomIndexByKey.get(endKey);
    if (Number.isInteger(start) && Number.isInteger(end)) {
      bonds.push([start, end]);
    }
  }

  for (let row = 0; row < rows; row += 1) {
    const rowOffset = row % 2 === 0 ? 0 : columnSpacing / 2;
    for (let column = 0; column < columns; column += 1) {
      const x = column * columnSpacing + rowOffset;
      const y = row * rowSpacing;
      const ripple = (row + column) % 2 === 0 ? 0.035 : -0.035;
      addAtom(`a-${row}-${column}`, x, y, ripple);
      addAtom(`b-${row}-${column}`, x, y + bondLength, -ripple);
    }
  }

  for (let row = 0; row < rows; row += 1) {
    for (let column = 0; column < columns; column += 1) {
      addBond(`a-${row}-${column}`, `b-${row}-${column}`);
      if (row > 0) {
        addBond(`a-${row}-${column}`, `b-${row - 1}-${column}`);
        addBond(
          `a-${row}-${column}`,
          `b-${row - 1}-${column + (row % 2 === 0 ? -1 : 1)}`
        );
      }
    }
  }

  return {
    id: "graphene",
    name: "Graphene Patch",
    formula: "C60",
    format: "app-coordinates",
    source: "curated approximate sheet",
    atoms,
    bonds,
  };
}

