#!/usr/bin/env node

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT_DIR = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const CLAUDE_PATH = "CLAUDE.md";
const FLOOR_HEADING = "## Floor that applies before and regardless of that read";
const NEXT_HEADING = "## Scope note";
const SOURCE_PATHS = [
  "AGENTS.md",
  "reference/op/operator-explanation-standard.md",
  "content/markdown/aaa/archie/academic-style-guide.md",
];

const args = new Set(process.argv.slice(2));
const wantsHelp = args.has("--help") || args.has("-h");
const wantsWrite = args.has("--write");
const wantsCheck = args.has("--check");
const unknownArgs = [...args].filter(
  (arg) => !["--check", "--write", "--help", "-h"].includes(arg)
);

if (wantsHelp) {
  printUsage(0);
}
if (unknownArgs.length) {
  console.error(`Unknown argument(s): ${unknownArgs.join(", ")}`);
  printUsage(2);
}
if (wantsWrite && wantsCheck) {
  console.error("Use either --check or --write, not both.");
  printUsage(2);
}

const absoluteClaudePath = path.join(ROOT_DIR, CLAUDE_PATH);
if (!fs.existsSync(absoluteClaudePath)) {
  console.error(`[claude-bootstrap-floor] missing ${CLAUDE_PATH}`);
  process.exit(1);
}

const current = fs.readFileSync(absoluteClaudePath, "utf8");
const expected = replaceFloor(current, buildFloor());
const mode = wantsWrite ? "write" : "check";

if (mode === "write") {
  fs.writeFileSync(absoluteClaudePath, expected, "utf8");
  console.log(`[claude-bootstrap-floor] wrote generated floor in ${CLAUDE_PATH}`);
  process.exit(0);
}

if (current !== expected) {
  console.error(`[claude-bootstrap-floor] generated floor in ${CLAUDE_PATH} is stale`);
  console.error("Review the changed authorities, then run: node scripts/build-claude-bootstrap-floor.mjs --write");
  process.exit(1);
}

console.log(`[claude-bootstrap-floor] generated floor in ${CLAUDE_PATH} is current`);

function printUsage(exitCode) {
  console.log("Usage: node scripts/build-claude-bootstrap-floor.mjs [--check|--write]");
  console.log(`  --check   Validate the generated floor in ${CLAUDE_PATH} (default)`);
  console.log(`  --write   Regenerate only the floor section in ${CLAUDE_PATH}`);
  process.exit(exitCode);
}

function buildFloor() {
  const fingerprints = SOURCE_PATHS.map(sourceFingerprint)
    .map(({ sourcePath, hash }) => `${sourcePath}=${hash}`)
    .join("; ");

  return [
    "<!-- Generated by scripts/build-claude-bootstrap-floor.mjs. Do not edit this section by hand. -->",
    "",
    "This is a compact pre-read safety projection, not an independent policy source. It applies only until the required reads above are complete; [AGENTS.md](AGENTS.md) and its named owners govern every detail and any tension. A changed source fingerprint makes the repository check fail so the projection must be reviewed before regeneration.",
    "",
    "- **Repository safety.** Do not execute git commands or read `.git`; git belongs exclusively to Codex. Use ordinary file reads and searches to inspect the working set, treat unrelated dirty state as normal, and report it only when it blocks the task or creates overwrite risk.",
    "- **Theory and evidence.** Standard physics is a recovery target or observer-level constraint, never an architrino-level premise. At that level use only $\\mathbb{A}\\mathbb{A}\\mathbb{A}$ primitives; architrinos have no physical mass, and the master equation gives acceleration rather than force. Use causal-delay terminology, set $c_f=1$ in every new numerical instantiation, grade claims as derived, measured, inferred, or guessed, name the instrument and domain for measurements, state checkable falsifiers, and never treat shared-code or replay agreement as independent evidence.",
    "- **Operator communication.** [The operator explanation standard](reference/op/operator-explanation-standard.md) is the sole authority. Until it is read, assume the operator knows $\\mathbb{A}\\mathbb{A}\\mathbb{A}$, define imported apparatus in place, write plainly, and do not compress away necessary explanation. Capture substantive ideas in both the thread and the owning priorities as they emerge. End substantive final responses with numbered next possible actions and a recommendation for each.",
    "- **Python.** Use the shared venv at `$AAA_VENV`, falling back to `../.venv`, rather than system Python.",
    "",
    `<!-- Source fingerprints: ${fingerprints} -->`,
  ].join("\n");
}

function replaceFloor(document, floor) {
  const floorStart = document.indexOf(FLOOR_HEADING);
  const nextStart = document.indexOf(NEXT_HEADING);
  if (floorStart === -1 || nextStart === -1 || nextStart <= floorStart) {
    throw new Error(`Expected ${FLOOR_HEADING} followed by ${NEXT_HEADING} in ${CLAUDE_PATH}`);
  }

  const floorContentStart = floorStart + FLOOR_HEADING.length;
  return `${document.slice(0, floorContentStart)}\n\n${floor}\n\n${document.slice(nextStart)}`;
}

function sourceFingerprint(sourcePath) {
  const absolutePath = path.join(ROOT_DIR, sourcePath);
  if (!fs.existsSync(absolutePath)) {
    throw new Error(`Missing source file: ${sourcePath}`);
  }
  const source = fs.readFileSync(absolutePath, "utf8");
  const hash = crypto.createHash("sha256").update(source).digest("hex").slice(0, 16);
  return { sourcePath, hash };
}
