from __future__ import annotations

import re

from scripts.pdg.pdgfeed_model import ParticleMapping, RequestOccurrenceTemplate


def _occurrence(assembly_id: str, title: str) -> RequestOccurrenceTemplate:
    return RequestOccurrenceTemplate(assembly_id=assembly_id, title=title)


def _mapping(
    *,
    canonical_name: str,
    canonical_id: str,
    full_name: str,
    aaa_notation: str,
    particle_type: str,
    family: str,
    generation: str,
    polarity: str,
    electrino_count: int,
    positrino_count: int,
    aliases: tuple[str, ...] = (),
    request_translation: str = "none",
    request_occurrences: tuple[RequestOccurrenceTemplate, ...] = (),
) -> ParticleMapping:
    return ParticleMapping(
        canonical_name=canonical_name,
        canonical_id=canonical_id,
        full_name=full_name,
        aaa_notation=aaa_notation,
        particle_type=particle_type,
        family=family,
        generation=generation,
        polarity=polarity,
        electrino_count=electrino_count,
        positrino_count=positrino_count,
        template_id=canonical_id,
        aliases=(canonical_name, *aliases),
        request_translation=request_translation,
        request_occurrences=request_occurrences,
    )


