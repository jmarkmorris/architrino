PDG_MAPPING_BY_CANONICAL_NAME = {
    mapping.canonical_name: mapping
    for mapping in PDG_PARTICLE_MAPPINGS
}

PDG_CANONICAL_NAME_BY_ALIAS = {
    alias: mapping.canonical_name
    for mapping in PDG_PARTICLE_MAPPINGS
    for alias in mapping.aliases
}

PHI_ENERGY_LEVEL_PATTERN = re.compile(r"^phi\(\d+(?:\.\d+)?\)(?:0|\+|-)?$")

REQUEST_ASSEMBLY_MAPPINGS: tuple[ParticleMapping, ...] = tuple(
    mapping
    for mapping in PDG_PARTICLE_MAPPINGS
    if mapping.particle_type == "assembly"
)

REQUEST_ASSEMBLY_IDS: tuple[str, ...] = tuple(mapping.canonical_id for mapping in REQUEST_ASSEMBLY_MAPPINGS)

REQUEST_ASSEMBLY_COUNTS = {
    mapping.canonical_id: {
        "electrinoCount": mapping.electrino_count,
        "positrinoCount": mapping.positrino_count,
    }
    for mapping in REQUEST_ASSEMBLY_MAPPINGS
}


def canonicalize_pdg_name(name: str) -> str:
    stripped = str(name).strip()
    if not stripped:
        return stripped
    if stripped in PDG_CANONICAL_NAME_BY_ALIAS:
        return PDG_CANONICAL_NAME_BY_ALIAS[stripped]
    lowered = stripped.lower()
    if PHI_ENERGY_LEVEL_PATTERN.fullmatch(lowered):
        return "phi"
    return PDG_CANONICAL_NAME_BY_ALIAS.get(lowered, stripped)


def lookup_particle_mapping(name: str) -> ParticleMapping | None:
    return PDG_MAPPING_BY_CANONICAL_NAME.get(canonicalize_pdg_name(name))
