#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { randomUUID, createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { parseBorgCertifiedBudgetIdentities } from "../../src/apps/borg/BorgCertifiedBudgetIdentityContract.js";

export const BUDGET_IDENTITIES_SOURCE_PATH = "src/apps/borg/data/certified-budget-identities.v1.json";
export const BUDGET_IDENTITIES_PROJECTION_PATH = "content/generated/borg/certified-budget-identities.v1.js";
const ROOT = fileURLToPath(new URL("../../", import.meta.url));
const REBUILD = "node scripts/borg/build-certified-budget-identities.mjs --write";

export function renderBorgCertifiedBudgetIdentities(sourceText) {
  const data = parseBorgCertifiedBudgetIdentities(sourceText);
  for (const row of Object.values(data.presets)) {
    if (createHash("sha256").update(row.allocationCanonicalJson).digest("hex") !== row.allocationHash) {
      throw new TypeError("Recorded budget hash does not match its retained applicability.");
    }
  }
  // Only serialized JSON is emitted. No source evaluation, model computation,
  // timestamps, host paths, or independently authored expected identities.
  return "// Generated by scripts/borg/build-certified-budget-identities.mjs. Do not edit.\n" +
    `// Authored data: ${BUDGET_IDENTITIES_SOURCE_PATH}\n` +
    "// Retained budget identities only; no new scientific acceptance authority.\n" +
    `export default ${JSON.stringify(data, null, 2)};\n`;
}

const identity = (stat) => [stat.dev, stat.ino, stat.size, stat.mtimeNs, stat.ctimeNs].join(":");

export function buildBorgCertifiedBudgetIdentities({ rootDir = ROOT, mode = "check" } = {}) {
  if (!["write", "check"].includes(mode)) throw new TypeError("Choose write or check.");
  const sourcePath = path.resolve(rootDir, BUDGET_IDENTITIES_SOURCE_PATH);
  const outputPath = path.resolve(rootDir, BUDGET_IDENTITIES_PROJECTION_PATH);
  const before = fs.lstatSync(sourcePath, { bigint: true });
  if (!before.isFile() || before.isSymbolicLink() || fs.realpathSync(sourcePath) !== sourcePath) {
    throw new TypeError("Budget identities source must be a canonical regular file.");
  }
  const recheck = () => {
    const current = fs.lstatSync(sourcePath, { bigint: true });
    if (!current.isFile() || identity(current) !== identity(before) ||
        fs.realpathSync(sourcePath) !== sourcePath) throw new Error("Budget identities source changed during generation.");
  };
  const fd = fs.openSync(sourcePath, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW | fs.constants.O_NONBLOCK);
  let bytes;
  try {
    if (identity(fs.fstatSync(fd, { bigint: true })) !== identity(before)) {
      throw new Error("Budget identities source changed during capture.");
    }
    bytes = fs.readFileSync(fd);
    if (identity(fs.fstatSync(fd, { bigint: true })) !== identity(before)) {
      throw new Error("Budget identities source changed during capture.");
    }
  } finally { fs.closeSync(fd); }
  recheck();
  const rendered = renderBorgCertifiedBudgetIdentities(new TextDecoder("utf-8", { fatal: true }).decode(bytes));
  recheck();
  let current = null;
  try {
    const stat = fs.lstatSync(outputPath);
    if (!stat.isFile() || stat.isSymbolicLink() || fs.realpathSync(outputPath) !== outputPath) {
      throw new TypeError("Budget identities projection must be a canonical regular file.");
    }
    current = fs.readFileSync(outputPath, "utf8");
  } catch (error) { if (error.code !== "ENOENT") throw error; }
  if (current === rendered) { recheck(); return { status: "current", path: BUDGET_IDENTITIES_PROJECTION_PATH }; }
  if (mode === "check") throw new Error(`Borg budget identities projection missing or stale; run ${REBUILD}`);
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  if (fs.realpathSync(path.dirname(outputPath)) !== path.dirname(outputPath)) {
    throw new TypeError("Budget identities projection directory must be canonical.");
  }
  const temporaryPath = `${outputPath}.${randomUUID()}.tmp`;
  try {
    fs.writeFileSync(temporaryPath, rendered, { flag: "wx" });
    recheck();
    fs.renameSync(temporaryPath, outputPath);
  } finally { if (fs.existsSync(temporaryPath)) fs.unlinkSync(temporaryPath); }
  return { status: "written", path: BUDGET_IDENTITIES_PROJECTION_PATH };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length !== 1 || !["--write", "--check"].includes(args[0])) {
    throw new TypeError("Usage: node scripts/borg/build-certified-budget-identities.mjs --write|--check");
  }
  console.log(JSON.stringify(buildBorgCertifiedBudgetIdentities({ mode: args[0].slice(2) })));
}
