import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(SCRIPT_DIR, "..");
const OUTPUT_PATH = resolve(REPO_ROOT, ".tmp/composer-header-signature.json");
const GENERATED_COMMENT = "Generated by scripts/generate-composer-header-signature.mjs";

function runGit(args) {
  try {
    return execFileSync("git", args, {
      cwd: REPO_ROOT,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch (_error) {
    return "";
  }
}

function readFileIfPresent(path) {
  try {
    return readFileSync(path, "utf8");
  } catch (_error) {
    return null;
  }
}

function buildSignaturePayload() {
  const shortSha = runGit(["rev-parse", "--short", "HEAD"]) || "unknown";
  const dirtyStatus = runGit(["status", "--short", "--untracked-files=no"]);
  return {
    comment: GENERATED_COMMENT,
    shortSha,
    dirty: dirtyStatus.length > 0,
    generatedAt: new Date().toISOString(),
  };
}

function writeSignatureFile() {
  const payload = buildSignaturePayload();
  const nextContent = `${JSON.stringify(payload, null, 2)}\n`;
  mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
  const previousContent = readFileIfPresent(OUTPUT_PATH);
  if (previousContent === nextContent) {
    process.stdout.write(`signature unchanged: ${OUTPUT_PATH}\n`);
    return;
  }
  writeFileSync(OUTPUT_PATH, nextContent, "utf8");
  process.stdout.write(`signature wrote: ${OUTPUT_PATH}\n`);
}

writeSignatureFile();
